#!/usr/bin/env node
/**
 * Regenerate `src/lib/bookFontData.js` — the brand book's embedded typefaces.
 *
 * jsPDF ships only the PDF base-14 (Helvetica / Times / Courier), so anything
 * else has to travel inside the file as TrueType data. The book is designed in
 * Archivo and Lora, so those six faces are instanced from the upstream
 * variable fonts, subset to the character range `pdfSafeText()` already
 * guarantees, and written out as base64.
 *
 * The subset is what keeps this affordable: the full variable Archivo is
 * ~640 KB on its own, while one instanced-and-subset face is ~21 KB. All six
 * together are ~173 KB of base64, and they load in the PDF's own lazy chunk —
 * nothing downloads them until someone actually builds a book.
 *
 * Checked in on purpose. A brand book that only renders correctly when
 * fonts.gstatic.com answers is a deliverable with a network dependency, and
 * this repo already had one font host take the book down (see the
 * "unreachable font host" fix on main).
 *
 * Requires: python3 with `fonttools` and `brotli` (pip install fonttools brotli)
 * and network access to raw.githubusercontent.com.
 *
 * Usage: node scripts/build-book-fonts.mjs
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const REPO = path.resolve(HERE, '..')
const GF = 'https://raw.githubusercontent.com/google/fonts/main'

/* The range `pdfSafeText()` folds everything else down into. Asking for more
   would embed glyphs no export can ever reach. */
const UNICODES = 'U+0020-007E,U+00A0-00FF'

const SOURCES = {
  archivo: `${GF}/ofl/archivo/Archivo%5Bwdth,wght%5D.ttf`,
  lora: `${GF}/ofl/lora/Lora%5Bwght%5D.ttf`,
  loraItalic: `${GF}/ofl/lora/Lora-Italic%5Bwght%5D.ttf`,
}

const FACES = [
  { name: 'archivoBold', src: 'archivo', axes: { wght: 700, wdth: 100 }, label: 'Archivo Bold (700)' },
  { name: 'archivoExtraBold', src: 'archivo', axes: { wght: 800, wdth: 100 }, label: 'Archivo ExtraBold (800)' },
  { name: 'archivoBlack', src: 'archivo', axes: { wght: 900, wdth: 100 }, label: 'Archivo Black (900)' },
  { name: 'loraRegular', src: 'lora', axes: { wght: 400 }, label: 'Lora Regular (400)' },
  { name: 'loraSemiBold', src: 'lora', axes: { wght: 600 }, label: 'Lora SemiBold (600)' },
  { name: 'loraItalic', src: 'loraItalic', axes: { wght: 400 }, label: 'Lora Italic (400)' },
]

const work = fs.mkdtempSync(path.join(os.tmpdir(), 'book-fonts-'))
const py = (args) => execFileSync('python3', args, { stdio: ['ignore', 'ignore', 'inherit'] })

async function download(url, dest) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} fetching ${url}`)
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()))
}

for (const [key, url] of Object.entries(SOURCES)) {
  await download(url, path.join(work, `${key}.ttf`))
}

const chunks = []
for (const face of FACES) {
  const inst = path.join(work, `${face.name}-inst.ttf`)
  const out = path.join(work, `${face.name}.ttf`)
  py([
    '-m', 'fontTools.varLib.instancer', path.join(work, `${face.src}.ttf`),
    ...Object.entries(face.axes).map(([k, v]) => `${k}=${v}`),
    '-o', inst,
  ])
  py([
    '-m', 'fontTools.subset', inst,
    `--unicodes=${UNICODES}`,
    '--layout-features=',
    '--no-hinting',
    '--desubroutinize',
    '--drop-tables+=GSUB,GPOS,GDEF,DSIG,MVAR,STAT,FFTM',
    `--output-file=${out}`,
  ])
  const b64 = fs.readFileSync(out).toString('base64')
  const lines = b64.match(/.{1,100}/g)
  chunks.push(
    `/* ${face.label} */\nexport const ${face.name} =\n` +
      lines.map((l, i) => `  '${l}'${i === lines.length - 1 ? '' : ' +'}`).join('\n') +
      '\n'
  )
  console.log(`${face.label.padEnd(24)} ${String(b64.length).padStart(7)} base64 chars`)
}

const header = `/**
 * Base64 TrueType data for the brand book's own typography.
 *
 * Archivo (700 / 800 / 900) and Lora (400 / 600 / 400 italic), instanced from
 * the upstream variable fonts and subset to the WinAnsi range \`pdfSafeText\`
 * already guarantees (U+0020-007E, U+00A0-00FF). Layout tables are dropped:
 * jsPDF does not shape, so GSUB/GPOS would be dead weight in every export.
 *
 * These are the book's fonts, not the client's. A brand book is a designed
 * document in its own right, and its chrome must not change shape because a
 * project picked a different heading face. The client's typefaces are named
 * and specified on the Typography page instead.
 *
 * Both families are SIL Open Font License 1.1 - see \`bookFonts.LICENSE.txt\`.
 * Regenerated by \`scripts/build-book-fonts.mjs\`; do not hand-edit.
 */

`

fs.writeFileSync(path.join(REPO, 'src/lib/bookFontData.js'), header + chunks.join('\n'))
fs.rmSync(work, { recursive: true, force: true })
console.log('\nwrote src/lib/bookFontData.js')
